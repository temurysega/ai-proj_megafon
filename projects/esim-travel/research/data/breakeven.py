# Порог «доля инкрементальных покупателей eSIM» при каннибализации роуминга. ВСЕ входы — допущения (уточнить на внутренних данных).
E = 1050      # выручка с одной туристической eSIM, ₽ (ориентир: Билайн 30 ГБ Европа, C005)
for m_e in (0.2, 0.3, 0.4):               # маржа eSIM
  for R in (1500, 2500, 4000):            # роуминговая выручка с поездки у «каннибализируемого» клиента, ₽ (≈ 3–8 суток по ~500 ₽, C012)
    for m_r in (0.5, 0.7):                # маржа роуминга
      gain = E*m_e; loss = R*m_r - gain
      # p*gain = (1-p)*loss  =>  p = loss/(gain+loss)
      p = loss/(gain+loss) if loss>0 else 0
      print(f"m_e={m_e:.1f} R={R} m_r={m_r:.1f}  выигрыш/инкр.={gain:.0f}  потеря/канн.={loss:.0f}  порог доли инкрементальных={p*100:.0f}%")
