# --- Сравнение на одном маршруте при одинаковом потреблении (исправлено 18.11.2026 по внешнему ревью) ---
# Раньше суточный роуминг в Китае делили на цену европейского пакета Билайна (30 ГБ, весь объём) — разные страны и потребление.
# Сценарий: Китай, поездка 7 дней, 5 ГБ. Источники: C012 (суточный роуминг 489–590 ₽/день, неделя 3 423–4 130 ₽),
# C013 (МТС 5 ГБ на неделю — 1 150 ₽; eSIMNow 5 ГБ на 30 дней — 490 ₽), C014 (МегаФон «Интернет M» 5 ГБ на 30 дней — 1 799 ₽).
days, need_gb = 7, 5
roam_week = (roam_day[0] * days, roam_day[1] * days)          # суточная опция покрывает до ~1 ГБ в день, 5 ГБ за неделю укладываются
packs = {"МТС, 5 ГБ на неделю": 1150, "МегаФон «Интернет M», 5 ГБ на 30 дней": 1799, "eSIMNow, 5 ГБ на 30 дней": 490}
print(f"\nКитай, {days} дней, {need_gb} ГБ: суточный роуминг {roam_week[0]}–{roam_week[1]} ₽")
for name, price in packs.items():
    print(f"  {name}: {price} ₽ → суточный роуминг дороже в {roam_week[0] / price:.1f}–{roam_week[1] / price:.1f} раза")
