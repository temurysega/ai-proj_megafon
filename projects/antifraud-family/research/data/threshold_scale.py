"""Одна шкала для порога окупаемости и результата пилота.
# inputs: economics_assumptions.yaml
# outputs: threshold_scale.md, threshold_scale.json

Порог окупаемости [C065] задан как относительное снижение МЕСЯЧНОГО оттока домохозяйства, а пилот измеряет КВАРТАЛЬНЫЙ отток
(3 месяца акции). Здесь оба переводятся в абсолютную разницу квартального оттока (п.п.) при постоянном месячном риске:
квартальный отток Q = 1 − (1 − p)^3, с защитой p' = p·(1 − r), разница ΔQ = Q(p) − Q(p').
"""
import json
from pathlib import Path

import yaml

HERE = Path(__file__).parent
A = yaml.safe_load((HERE / "economics_assumptions.yaml").read_text(encoding="utf-8")) or {}

BASES = [0.010, 0.015, 0.025]            # месячный отток домохозяйства, диапазон допущения C056 (1–2,5%), центр 1,5%
THRESHOLDS = {                            # относительное снижение месячного оттока, нужное для окупаемости [C065]
    "C — бесплатная база + платный слой": (0.027, 0.041, BASES),
    "защита ранее неплатящих семей": (0.013, 0.047, BASES),
    "B — всем бесплатно": (0.04, 0.21, [0.015]),  # в C065 диапазон 4–21% посчитан для оттока 1,5%/мес
}


def quarterly(p: float) -> float:
    return 1 - (1 - p) ** 3


def delta_pp(p: float, r: float) -> float:
    return 100 * (quarterly(p) - quarterly(p * (1 - r)))


rows, out = [], {"bases_monthly": BASES, "thresholds": {}}
for name, (lo, hi, bases) in THRESHOLDS.items():
    out["thresholds"][name] = {}
    for p in bases:
        q = quarterly(p)
        d_lo, d_hi = delta_pp(p, lo), delta_pp(p, hi)
        out["thresholds"][name][f"{p:.3f}"] = {"control_quarterly_pct": round(100 * q, 3),
                                               "delta_pp": [round(d_lo, 3), round(d_hi, 3)],
                                               "relative_quarterly_pct": [round(100 * d_lo / (100 * q), 2), round(100 * d_hi / (100 * q), 2)]}
        rows.append(f"| {name} | {100 * p:.1f}% | {100 * lo:.1f}–{100 * hi:.1f}% | {100 * q:.2f}% | "
                    f"{d_lo:.3f}–{d_hi:.3f} п.п. | {100 * d_lo / (100 * q):.1f}–{100 * d_hi / (100 * q):.1f}% |")

check = delta_pp(0.015, 0.04)  # пример внешнего ревью: 1,5% → 1,44% в месяц ≈ 0,175 п.п. за квартал
out["example_1_5pct_4pct_delta_pp"] = round(check, 4)
md = ["# Порог окупаемости и результат пилота в одной шкале", "",
      "_Порог [C065] — относительное снижение месячного оттока; пилот измеряет квартальный отток. Ниже оба в п.п. квартального оттока "
      "при постоянном месячном риске: Q = 1 − (1 − p)^3._", "",
      "| Порог | Месячный отток контроля | Нужное снижение месячного оттока | Квартальный отток контроля | Нужная разница квартального оттока | То же, относительно квартального |",
      "|---|---|---|---|---|---|", *rows, "",
      f"**Проверка:** при месячном оттоке 1,5% снижение на 4% даёт 1,44% в месяц и {check:.3f} п.п. квартального оттока.",
      "", "**Как применять:** в пилоте считаем абсолютную разницу квартального оттока (контроль − предложение, п.п.) и её 95% ДИ, "
      "фактический месячный отток контроля берём из выгрузки K1 и по таблице (или скрипту) переводим порог в п.п. при этом оттоке. "
      "Относительное снижение квартального оттока почти совпадает с относительным снижением месячного (последний столбец), поэтому "
      "таблица размеров выборки в `experiment_design.md` (эффект в % квартального оттока) сопоставима с порогами."]
(HERE / "threshold_scale.md").write_text("\n".join(md) + "\n", encoding="utf-8")
(HERE / "threshold_scale.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
print("\n".join(md))
